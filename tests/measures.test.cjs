'use strict';
const assert=require('node:assert/strict');
const m=require('../measures.js');
const example=m.calculate(m.DEFAULTS);
assert.equal(example.attainment8.total,81,'worked-example Attainment 8 must be 82');
assert.equal(Math.round(example.ebacc.aps*100)/100,7.67,'EBacc APS six positions without double weighting');
assert.equal(example.admissions.aps,7.8,'St Dominic\'s example mean must be 7.8');
assert.equal(example.ebacc.entered,true);
assert.equal(example.attainment8.english,16);
const noFrench=m.calculate({...m.DEFAULTS,french:null});
assert.equal(noFrench.ebacc.components.language,0);
assert.equal(noFrench.ebacc.entered,false);
assert.equal(noFrench.attainment8.total,81,'No French can still score same Attainment 8 with alternate EBacc subjects');
const noEnglishLiterature=m.calculate({...m.DEFAULTS,englishLiterature:null});
assert.equal(noEnglishLiterature.attainment8.english,7,'English is not doubled unless both papers sat');
assert.equal(noEnglishLiterature.ebacc.components.english,0,'EBacc English pillar requires both papers');
const combined=m.calculate({...m.DEFAULTS,biology:null,chemistry:null,physics:null,combined1:7,combined2:6});
assert.equal(combined.ebacc.components.science[0],7);
assert.equal(combined.ebacc.components.science[1],6);
assert.equal(combined.attainment8.ebaccSubjects.length,3);
const empty=m.calculate(Object.fromEntries(m.SUBJECTS.map(([k])=>[k,null])));
assert.equal(empty.attainment8.total,0);
assert.equal(empty.ebacc.aps,0);
assert.equal(empty.admissions.aps,null);
assert.equal(empty.attainment8.missingSlots,8);
console.log('Measures guide calculators: all assertions passed');
